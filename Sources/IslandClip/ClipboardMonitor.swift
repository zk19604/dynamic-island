import AppKit

/// Watches the general pasteboard for new text.
///
/// macOS has no "clipboard changed" notification, so this polls
/// `changeCount` (a cheap integer read) every 0.5 s and only reads the
/// contents when it changes.
final class ClipboardMonitor {
    /// Types set by password managers and similar apps (see nspasteboard.org).
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    // TODO: Settings → "Ignore these apps": skip copies made while one of a
    // user-chosen list of apps is frontmost (NSWorkspace.frontmostApplication).

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private let onNewText: (String) -> Void

    init(onNewText: @escaping (String) -> Void) {
        self.onNewText = onNewText
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Constants.clipboardPollInterval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // Tolerance lets macOS batch wakeups, which keeps idle energy use low.
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// True when the user has set IslandClip to "Deny" in the pasteboard privacy settings (macOS 15.4+).
    var isAccessDenied: Bool {
        if #available(macOS 15.4, *) {
            return pasteboard.accessBehavior == .alwaysDeny
        }
        return false
    }

    /// Copies text back to the clipboard without recording it as a new copy.
    func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        // Checking types does not read the contents.
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard types.contains(.string), !types.contains(.fileURL) else { return }
        guard let text = pasteboard.string(forType: .string) else { return }
        onNewText(text)
    }
}
